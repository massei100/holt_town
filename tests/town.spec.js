import { expect, test } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { newRun } from '../src/game.js'

const artifacts = process.env.TOWN_SCREENSHOT_DIR
async function screenshot(page,name){
  if(!artifacts)return
  await mkdir(artifacts,{recursive:true})
  await page.screenshot({path:artifacts+'/'+name+'.png',scale:'css'})
}
function named(page,name){return page.getByRole('button',{name,exact:true})}
async function waitForMotion(page){await page.waitForTimeout(850)}
async function crossing(page,click){
  await expect(page.getByText('빨간불 · 기다려요').last()).toBeVisible({timeout:45000})
  await expect(named(page,'건너기')).toHaveCount(0)
  await screenshot(page,'crossing-red')
  await click('기다리기')
  await expect(named(page,'왼쪽 살피기')).toBeVisible({timeout:25000})
  await expect(named(page,'건너기')).toHaveCount(0)
  await click('왼쪽 살피기')
  await expect(named(page,'건너기')).toHaveCount(0)
  await click('오른쪽 살피기')
  await click('건너기')
  await expect(named(page,'들어가기')).toBeVisible({timeout:45000})
}
